def generate_profile_id(name: str) -> str:
    name_part = re.sub(r"\s+", "_", name.strip()) if name.strip() else "user"
    name_part = re.sub(r"[^A-Za-z0-9_-]", "", name_part) or "user"
    return normalize_user_id(f"{name_part}_{random.randint(1000, 9999)}")


def load_profile_into_session(profile_id: str) -> bool:
    saved_profile = get_user_profile(profile_id)
    if not saved_profile:
        return False

    st.session_state.user_profile = saved_profile
    st.session_state.profile_user_id = saved_profile["user_id"]
    st.session_state.profile_name_input = saved_profile.get("name", "")
    st.session_state.profile_id_input = saved_profile["user_id"]
    st.session_state.profile_id_autogenerated = False
    st.session_state.routine_mode = saved_profile.get("routine_mode")
    st.session_state.routine = saved_profile.get("routine", [])
    st.session_state.ar_days = saved_profile.get("ar_days", {})
    st.session_state.editing_profile = False
    st.session_state.creating_profile = False
    st.session_state.profile_storage_status = "loaded"
    return True


def on_profile_name_change():
    if not st.session_state.get("profile_id_autogenerated", True):
        return
    st.session_state.profile_id_input = generate_profile_id(
        st.session_state.get("profile_name_input", "")
    )


def on_profile_id_change():
    st.session_state.profile_id_autogenerated = False


def show_storage_status():
    storage_status = st.session_state.pop("profile_storage_status", None)
    if storage_status == "saved":
        st.success("Profile saved to Cloud SQL.")
    if storage_status == "loaded":
        st.success("Profile loaded.")
    if storage_status == "logged_out":
        st.success("Logged out.")


def logout_profile():
    """Clear the loaded profile and related in-session user context."""
    for key in (
        "profile_name_input",
        "profile_id_input",
        "profile_id_autogenerated",
        "load_profile_id",
        "routine_search",
        "routine_search_results",
        "routine_last_search",
        "adding_product",
        "show_product_details",
        "chat_messages",
        "chat_thread_id",
        "chat_shortcuts_hidden",
        "pending_shortcut",
        "interested_products",
    ):
        st.session_state.pop(key, None)

    st.session_state.user_profile = {}
    st.session_state.profile_user_id = "default"
    st.session_state.editing_profile = False
    st.session_state.creating_profile = False
    st.session_state.routine_mode = None
    st.session_state.routine = []
    st.session_state.ar_days = {}
    st.session_state.profile_storage_status = "logged_out"


def show_profile_entry():
    st.title("👤 Profile")
    show_storage_status()
    st.markdown("### Are you a first-time user?")

    first_time, returning = st.columns(2)
    with first_time:
        with st.container(border=True):
            st.markdown("#### First time user")
            st.caption("Create a profile and save it to Cloud SQL with your own profile ID.")
            if st.button("Create a new profile", type="primary", use_container_width=True):
                st.session_state.creating_profile = True
                st.session_state.editing_profile = True
                st.session_state.profile_id_autogenerated = True
                st.session_state.profile_name_input = ""
                st.session_state.profile_id_input = generate_profile_id("")
                st.rerun()

    with returning:
        with st.container(border=True):
            st.markdown("#### Returning user")
            load_id = st.text_input(
                "Profile ID",
                key="load_profile_id",
                placeholder="e.g. amy_1234",
                help="Load a profile saved in Cloud SQL.",
            )
            if st.button("Load profile", use_container_width=True):
                if load_profile_into_session(load_id):
                    st.rerun()
                else:
                    st.warning("No saved profile found for that ID.")


