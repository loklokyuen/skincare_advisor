def show_profile_view():
    profile = st.session_state.user_profile
    name = profile.get("name", "")
    show_storage_status()

    col_title, col_edit, col_logout = st.columns([5, 1, 1])
    with col_title:
        st.title(f"👤 Hi, {name}!" if name else "👤 Your Skin Profile")
        if profile.get("user_id"):
            st.caption(f"Profile ID: `{profile['user_id']}`")
    with col_edit:
        st.write("")
        if st.button("Edit", use_container_width=True, type="primary"):
            st.session_state.profile_name_input = profile.get("name", "")
            st.session_state.profile_id_input = profile.get("user_id", "")
            st.session_state.profile_id_autogenerated = False
            st.session_state.editing_profile = True
            st.rerun()
    with col_logout:
        st.write("")
        if st.button("Log out", use_container_width=True):
            logout_profile()
            st.rerun()

    skin_type = profile.get("skin_type", "")
    st.markdown(f"### {skin_type_badge(skin_type)} {skin_type} Skin")
    st.caption(skin_type_description(skin_type))

    if profile.get("age_range") and profile["age_range"] != "Prefer not to say":
        st.caption(f"Age range: {profile['age_range']}")
    if profile.get("sensitive_skin"):
        st.caption("Sensitive or reactive skin")

    concerns = profile.get("concerns", [])
    if concerns:
        st.divider()
        st.subheader("Skin Concerns")
        st.markdown(highlight_concerns(concerns), unsafe_allow_html=True)
        st.write("")

    goals = profile.get("goals", [])
    if goals:
        st.divider()
        st.subheader("Goals")
        st.markdown(
            " ".join(
                f'<span style="background:#e8f5e9;color:#2e7d32;padding:2px 8px;'
                f'border-radius:12px;margin:2px;font-size:0.8rem">{g}</span>'
                for g in goals
            ),
            unsafe_allow_html=True,
        )
        st.write("")

    notes = str(profile.get("notes") or "").strip()
    if notes:
        st.divider()
        st.subheader("Notes")
        st.write(notes)

    flags = []
    if profile.get("avoid_fragrance"):
        flags.append("🌿 Fragrance-free")
    if profile.get("avoid_alcohol"):
        flags.append("🚫 Alcohol-free")
    if profile.get("avoid_parabens"):
        flags.append("✅ Paraben-free")
    if profile.get("avoid_silicones"):
        flags.append("🔵 Silicone-free")
    if profile.get("pref_vegan"):
        flags.append("🌱 Vegan")
    if profile.get("pref_cruelty_free"):
        flags.append("🐰 Cruelty-free")
    if profile.get("pref_reef_safe"):
        flags.append("🐠 Reef-safe")

    if flags:
        st.divider()
        st.subheader("Preferences")
        cols = st.columns(min(len(flags), 4))
        for i, flag in enumerate(flags):
            with cols[i % 4]:
                st.markdown(f"`{flag}`")

    allergens = profile.get("allergens", [])
    if allergens:
        st.divider()
        st.subheader("Known Allergens")
        for a in allergens:
            st.markdown(f"- {a}")


# ── Init session state ─────────────────────────────────────────────────────────
if "user_profile" not in st.session_state:
    st.session_state.user_profile = {}
if "editing_profile" not in st.session_state:
    st.session_state.editing_profile = False
if "profile_user_id" not in st.session_state:
    st.session_state.profile_user_id = st.session_state.user_profile.get("user_id", "default")
if "creating_profile" not in st.session_state:
    st.session_state.creating_profile = False

has_profile = bool(st.session_state.user_profile.get("skin_type"))

if not has_profile and not st.session_state.editing_profile:
    show_profile_entry()
elif not has_profile or st.session_state.editing_profile:
    if has_profile and st.session_state.editing_profile:
        if st.button("← Back"):
            st.session_state.editing_profile = False
            st.rerun()
    show_profile_form()
else:
    show_profile_view()
